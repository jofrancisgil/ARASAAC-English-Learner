export const getCategoryById = (
  id: string,
  allCategories: SemanticCategory[] = SEMANTIC_CATEGORIES
): SemanticCategory => {
  const found = allCategories.find((c) => c.id === id);
  if (found) return found;

  // Fallback for custom or unknown categories
  return {
    id,
    name: id.charAt(0).toUpperCase() + id.slice(1),
    iconName: 'Tag',
    emoji: '🏷️',
    description: 'Custom vocabulary category',
    pastelBg: 'bg-teal-50 hover:bg-teal-100/80',
    pastelBorder: 'border-teal-200',
    pastelText: 'text-teal-800',
    badgeBg: 'bg-teal-100 text-teal-800',
    aacColorCode: '#E0F2FE',
  };
};
